// Generates supabase/seed.sql and supabase/tests/005_seed_parity.test.sql from the prototype seed
// (app/src/lib/data/seed.ts — PLAN §2.7). Never hand-edit either output: run `npm run db:seed`.
//
// The seed inserts only stored fields. total / total_paid / status are left to the DB triggers, and the
// parity test asserts they come out equal to the prototype's own ledger for every booking.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { seedDb } from "@/lib/data/seed";

const root = join(import.meta.dirname, "..", "..");
const db = seedDb();
const seedCrew = db.crew.filter((c) => !c.userId); // linked entries come from the profiles trigger (migration 014)

/** Stable uuid for a prototype text id (seed only — real rows use gen_random_uuid()). */
const uuid = (key: string) => {
  const h = createHash("md5").update(`bs.moment-seed:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
};
const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
/** Prototype ISODate (Asia/Jakarta calendar day) → timestamptz at local midnight. */
const day = (d: string | null) => (d ? q(`${d}T00:00:00+07:00`) : "null");
const rows = (lines: string[]) => lines.join(",\n");
/** created_at that preserves the prototype's array order (lists sort by it; new rows append after). */
const seq = (i: number) => q(new Date(Date.UTC(2026, 0, 1, 0, i)).toISOString());

const WORKSPACE = uuid("workspace:bs.moment");
const s = db.settings;
const out: string[] = [];
out.push(`-- GENERATED by app/scripts/gen-seed-sql.ts from app/src/lib/data/seed.ts — do not edit. Local + staging only.
-- ${db.packages.length} packages · ${seedCrew.length} crew · ${db.bookings.length} bookings · ${db.invoices.length} invoices.
-- created_by / canceled_by stay null until P4 creates real users (the prototype stores the text "Admin").

begin;

-- One workspace; every row names it (migration 017 has no default).
insert into public.workspaces (id, slug, name) values (${q(WORKSPACE)}, 'main', ${q(s.business.name)});

insert into public.workspace_settings (workspace_id, business_name, business_address, business_email, business_phone, default_terms, default_payment) values
(${q(WORKSPACE)}, ${q(s.business.name)}, ${q(s.business.address)}, ${q(s.business.email)}, ${q(s.business.phone)}, ${q(s.defaultTerms)}, ${json(s.defaultPayment)});
`);

out.push(`insert into public.packages (workspace_id, id, name, price, summary, description, is_active, archived_at, created_at, updated_at) values
${rows(db.packages.map((p, i) => `(${q(WORKSPACE)}, ${q(uuid(p.id))}, ${q(p.name)}, ${p.price}, ${q(p.summary)}, ${q(p.description)}, ${p.isActive}, ${day(p.archivedAt)}, ${seq(i)}, ${day(p.updatedAt)})`))};
`);

out.push(`insert into public.crew (workspace_id, id, name, role, is_active, created_at) values
${rows(seedCrew.map((c, i) => `(${q(WORKSPACE)}, ${q(uuid(c.id))}, ${q(c.name)}, ${q(c.role)}, ${c.isActive}, ${seq(i)})`))};
`);

out.push(`insert into public.bookings (workspace_id, id, ref, booking_name, client_name, client_phone, package_id, package_name_snapshot, package_price_snapshot, booking_date, event_start, location, notes, terms, payment_instruction, canceled_at, cancel_reason, created_at, updated_at) values
${rows(
  db.bookings.map(
    (b) =>
      `(${q(WORKSPACE)}, ${q(uuid(b.id))}, ${q(b.ref)}, ${q(b.bookingName)}, ${q(b.clientName)}, ${q(b.clientPhone)}, ${q(uuid(b.packageId))}, ${q(b.packageNameSnapshot)}, ${b.packagePriceSnapshot}, ${q(b.bookingDate)}, ${q(b.eventStart)}, ${q(b.location)}, ${q(b.notes)}, ${q(b.terms)}, ${json(b.paymentInstruction)}, ${q(b.canceledAt)}, ${q(b.cancelReason)}, ${q(b.createdAt)}, ${q(b.updatedAt)})`,
  ),
)};
`);

const items = db.bookings.flatMap((b) => b.items.map((i, k) => `(${q(WORKSPACE)}, ${q(uuid(i.id))}, ${q(uuid(b.id))}, ${q(i.name)}, ${i.price}, ${i.qty}, ${k})`));
out.push(`insert into public.booking_items (workspace_id, id, booking_id, name, price, qty, position) values
${rows(items)};
`);

const crew = db.bookings.flatMap((b) => b.crewIds.map((c, k) => `(${q(WORKSPACE)}, ${q(uuid(b.id))}, ${q(uuid(c))}, ${k})`));
out.push(`insert into public.booking_crew (workspace_id, booking_id, crew_id, position) values
${rows(crew)};
`);

// Issue order, so every insert sees the same paid-before as the prototype did.
const invoices = [...db.invoices].sort((a, b) => a.issuedAt.localeCompare(b.issuedAt));
out.push(`insert into public.invoices (workspace_id, id, booking_id, number, type, dp_method, dp_percentage, amount, snapshot, snapshot_hash, issued_at, created_at) values
${rows(
  invoices.map(
    (i) =>
      `(${q(WORKSPACE)}, ${q(uuid(i.id))}, ${q(uuid(i.bookingId))}, ${q(i.number)}, ${q(i.type)}, ${q(i.dpMethod)}, ${i.dpPercentage ?? "null"}, ${i.amount}, ${json(i.snapshot)}, ${q(i.snapshotHash)}, ${q(i.issuedAt)}, ${q(i.issuedAt)})`,
  ),
)};
`);

const counters = (kind: "booking" | "invoice") =>
  rows(Object.entries(db.counters[kind]).map(([year, n]) => `(${q(WORKSPACE)}, ${year}, ${n})`));
out.push(`-- Counters continue above the highest seeded number (prototype syncCounters).
insert into public.booking_counters (workspace_id, year, last_value) values
${counters("booking")};
insert into public.invoice_counters (workspace_id, year, last_value) values
${counters("invoice")};

commit;
`);

writeFileSync(join(root, "supabase", "seed.sql"), out.join("\n"));

// ── Parity test: DB-derived fields vs the prototype ledger ──────────────────────────────────────
const expected = db.bookings.map((b) => `(${q(b.ref)}, ${b.total}::bigint, ${b.totalPaid}::bigint, ${q(b.status)})`);
const byStatus = (st: string) => db.bookings.filter((b) => b.status === st).length;
const test = `-- GENERATED by app/scripts/gen-seed-sql.ts — do not edit.
-- The triggers must derive exactly the prototype ledger's total / total_paid / status for every seeded booking.
begin;
select plan(8);

select is((select count(*)::int from public.packages), ${db.packages.length}, 'seed: packages');
select is((select count(*)::int from public.packages where is_active), ${db.packages.filter((p) => p.isActive).length}, 'seed: active packages');
select is((select count(*)::int from public.crew where user_id is null), ${seedCrew.length}, 'seed: crew');
select is((select count(*)::int from public.bookings), ${db.bookings.length}, 'seed: bookings');
select is((select count(*)::int from public.invoices), ${db.invoices.length}, 'seed: invoices');

select set_eq(
  $$ select ref, total, total_paid, status from public.bookings $$,
  $$ values
${expected.map((e) => `       ${e}`).join(",\n")} $$,
  'seed parity: every booking total / total_paid / status equals the prototype ledger'
);

select results_eq(
  $$ select status, count(*)::int from public.bookings group by status order by status $$,
  $$ values ('canceled', ${byStatus("canceled")}), ('draft', ${byStatus("draft")}), ('paid', ${byStatus("paid")}), ('partially_paid', ${byStatus("partially_paid")}) $$,
  'seed: every status is covered, same counts as the prototype'
);

select is(
  (select next_invoice_number((select id from public.workspaces), 2026)),
  'INV-2026-${String(db.counters.invoice[2026] + 1).padStart(4, "0")}',
  'seed: invoice numbering continues above the highest seeded number'
);

select * from finish();
rollback;
`;
writeFileSync(join(root, "supabase", "tests", "005_seed_parity.test.sql"), test);

console.log(`seed.sql: ${db.packages.length} packages, ${seedCrew.length} crew, ${db.bookings.length} bookings, ${items.length} items, ${invoices.length} invoices`);
