// Generates src/components/ds/icon-paths.ts from the Figma icon export
// (public/__figma__/specs/F01-icons.json — CIR "Icons" section, 20×20, 1.5 stroke).
// The single icon colour (#202938 = text/primary) becomes currentColor.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const icons = JSON.parse(readFileSync(join(root, "public/__figma__/specs/F01-icons.json"), "utf8"));
const entries = Object.entries(icons)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, { svg }]) => {
    const inner = svg
      .replace(/^<svg[^>]*>\n?/, "")
      .replace(/<\/svg>\s*$/, "")
      .replace(/#202938/gi, "currentColor")
      .replace(/\s*\n\s*/g, "");
    return `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`;
  });
const out = `// GENERATED by scripts/build-icons.mjs from Figma CIR "Icons" — do not edit.
export const iconPaths = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof iconPaths;
`;
writeFileSync(join(root, "src/components/ds/icon-paths.ts"), out);
console.log(`icon-paths.ts: ${entries.length} icons`);
