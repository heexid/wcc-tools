// Generates src/styles/tokens.css from the Figma exports in tokens/.
// Source of truth: Figma "bs internal tools" → CIR variables + local styles.
// Re-run after every re-export:  npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vars = JSON.parse(readFileSync(join(root, "tokens/figma.tokens.json"), "utf8"));
const styles = JSON.parse(readFileSync(join(root, "tokens/figma.styles.json"), "utf8"));

const slug = (s) => s.toLowerCase().replace(/\s+/g, "-");
const leaves = [];
(function walk(node, path) {
  if (node && typeof node === "object" && "$value" in node) return leaves.push({ path, token: node });
  for (const [k, v] of Object.entries(node)) if (!k.startsWith("$")) walk(v, [...path, k]);
})(vars, []);

// Figma path → CSS custom property (Tailwind v4 namespace)
function cssName(path, type) {
  const [collection, ...rest] = path;
  if (type === "color") {
    const p = collection === "primitives" ? rest.slice(1) : rest; // drop "color/" on primitives
    return `--color-${p.join("-")}`;
  }
  const [group, ...name] = rest;
  if (collection !== "breakpoint" && group === "radius") return `--radius-${name.join("-")}`;
  if (collection !== "breakpoint" && group === "space") return `--spacing-${name.join("-")}`;
  return `--spacing-${rest.join("-")}`; // component + breakpoint dimensions (heights, widths, icons…)
}
const byRef = new Map(leaves.map((l) => [`{${l.path.join(".")}}`, cssName(l.path, l.token.$type)]));
const hex = (h) => (h.length === 9 && h.endsWith("FF") ? h.slice(0, 7) : h).toLowerCase();
const value = (t) => {
  const v = t.$value;
  if (typeof v === "string" && v.startsWith("{")) return `var(${byRef.get(v)})`;
  if (t.$type === "color") return hex(v);
  return `${v}px`;
};
const rgba = ({ r, g, b, a = 1 }) =>
  `rgb(${Math.round(r * 255)} ${Math.round(g * 255)} ${Math.round(b * 255)} / ${+a.toFixed(4)})`;

const weight = { Regular: 400, Medium: 500, "Semi Bold": 600, Bold: 700 };
// "Text/Body" → body, "Heading/Page" → heading-page, "UI/Button" → ui-button, "Display/Metric" → display-metric
const textName = (n) => slug(n.startsWith("Text/") ? n.slice(5) : n.replace("/", "-"));

const out = [];
out.push(`/* GENERATED by scripts/build-tokens.mjs from Figma "bs internal tools" — do not edit. */`);
out.push(`@theme static {`, `  --*: initial;`, ``);
out.push(`  /* Fonts */`, `  --font-sans: var(--font-inter), ui-sans-serif, system-ui, sans-serif;`);
for (const [n, w] of Object.entries(weight)) out.push(`  --font-weight-${slug(n).replace("-", "")}: ${w};`);
for (const section of ["primitives", "semantic", "component", "breakpoint"]) {
  out.push(``, `  /* ${section} (Figma variables) */`);
  for (const l of leaves.filter((l) => l.path[0] === section)) {
    const desc = l.token.$description ? ` /* ${l.token.$description.replace(/\*\//g, "")} */` : "";
    out.push(`  ${cssName(l.path, l.token.$type)}: ${value(l.token)};${desc}`);
  }
}
out.push(``, `  /* Text styles */`);
for (const t of styles.text) {
  const n = textName(t.name);
  out.push(`  --text-${n}: ${t.fontSize}px;`);
  out.push(`  --text-${n}--line-height: ${t.lineHeight}px;`);
  out.push(`  --text-${n}--font-weight: ${weight[t.fontStyle]};`);
  out.push(`  --text-${n}--letter-spacing: ${+t.letterSpacing.toFixed(2)}px;`);
}
out.push(``, `  /* Effect styles */`);
for (const e of styles.effects) {
  const inset = e.type === "INNER_SHADOW";
  const n = slug(e.name.split("/")[1]);
  out.push(`  --${inset ? "inset-shadow" : "shadow"}-${n}: ${inset ? "inset " : ""}${e.x}px ${e.y}px ${e.blur}px ${e.spread}px ${rgba(e.color)};`);
}
out.push(`}`, ``, `:root {`, `  /* Paint styles (use as bg-(image:--gradient-…)) */`);
for (const p of styles.paints) {
  const layers = p.layers.map((l) => {
    const stops = l.stops.map((s) => `${rgba({ ...s.color, a: s.color.a * l.opacity })} ${+(s.position * 100).toFixed(1)}%`);
    return `linear-gradient(${p.angle}deg, ${stops.join(", ")})`;
  });
  if (p.base) layers.push(rgba(p.base));
  out.push(`  --gradient-${slug(p.name.split("/")[1])}: ${layers.join(", ")};`);
}
out.push(`}`, ``);

// Manifest: Figma name → CSS var → resolved value (used by /dev/tokens and the G2 token test)
const resolveLeaf = (t) => {
  let cur = t;
  while (typeof cur.$value === "string" && cur.$value.startsWith("{")) {
    const path = cur.$value.slice(1, -1).split(".");
    cur = path.reduce((n, k) => n[k], vars);
  }
  return cur.$type === "color" ? hex(cur.$value) : cur.$value;
};
const manifest = {
  variables: leaves.map((l) => ({
    figma: `${l.token.$extensions?.["figma-console-mcp"]?.collectionId ? l.path[0] : ""}/${l.path.slice(1).join("/")}`,
    css: cssName(l.path, l.token.$type),
    type: l.token.$type,
    alias: typeof l.token.$value === "string" && l.token.$value.startsWith("{") ? byRef.get(l.token.$value) : null,
    value: resolveLeaf(l.token),
  })),
  text: styles.text.map((t) => ({ figma: t.name, css: `--text-${textName(t.name)}`, fontSize: t.fontSize, lineHeight: t.lineHeight, fontWeight: weight[t.fontStyle], letterSpacing: +t.letterSpacing.toFixed(2) })),
  effects: styles.effects.map((e) => ({ figma: e.name, css: `--${e.type === "INNER_SHADOW" ? "inset-shadow" : "shadow"}-${slug(e.name.split("/")[1])}` })),
  paints: styles.paints.map((p) => ({ figma: p.name, css: `--gradient-${slug(p.name.split("/")[1])}` })),
};

mkdirSync(join(root, "src/styles"), { recursive: true });
writeFileSync(join(root, "src/styles/tokens.css"), out.join("\n"));
writeFileSync(join(root, "src/styles/tokens.manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`tokens.css: ${leaves.length} variables, ${styles.text.length} text, ${styles.effects.length} effects, ${styles.paints.length} paints`);
